"""final.csv -> data/splits/*.txt image lists + stage{1,2}.yaml. Spec §5.

Fails if any test list shares an image path or a (source, group) with a train/val list.
Prints a viewpoint balance table for stage 2 and warns (only) if g2a/a2a drone images differ by >2x.

Usage:
  uv run scripts/build_splits.py
"""

import polars as pl

from common import CLASSES, DATA, MANIFESTS, SEED

SPLITS = DATA / "splits"
REPLAY_TRAIN, REPLAY_VAL = 10_000, 2_000
STAGE2_SOURCES = ["dut", "detfly", "aot", "aod4"]


def pick(df: pl.DataFrame, source: str, split: str) -> pl.DataFrame:
    return df.filter((pl.col("source") == source) & (pl.col("split") == split))


def sample(df: pl.DataFrame, n: int) -> pl.DataFrame:
    return df.sort("image").sample(min(n, len(df)), seed=SEED, shuffle=True).sort("image")


def write_list(name: str, df: pl.DataFrame) -> None:
    (SPLITS / f"{name}.txt").write_text("".join(f"{p}\n" for p in df["image"]), encoding="utf-8")


def write_yaml(name: str, train: str, val: str) -> None:
    names = "\n".join(f"  {i}: {c}" for i, c in enumerate(CLASSES))
    (SPLITS / f"{name}.yaml").write_text(
        f"# generated by scripts/build_splits.py\npath: {SPLITS.as_posix()}\ntrain: {train}.txt\nval: {val}.txt\nnames:\n{names}\n",
        encoding="utf-8",
    )


def main() -> None:
    df = pl.read_csv(MANIFESTS / "final.csv", schema_overrides={"group": pl.String})
    ser_tr, ser_va = pick(df, "seraphim", "train"), pick(df, "seraphim", "val")
    lists = {
        "stage1_train": ser_tr,
        "stage1_val": ser_va,
        "stage2_train": pl.concat([pick(df, s, "train") for s in STAGE2_SOURCES] + [sample(ser_tr, REPLAY_TRAIN)]),
        "stage2_val": pl.concat([pick(df, s, "val") for s in STAGE2_SOURCES] + [sample(ser_va, REPLAY_VAL)]),
        "test_antiuav": pick(df, "antiuav", "test"),
        "test_detfly": pick(df, "detfly", "test"),
        "test_aot_drone": pick(df, "aot", "test_aux"),
        "test_dut": pick(df, "dut", "test_aux"),
        "test_fa": pick(df, "aot", "test_fa"),
    }

    # every row of final.csv must land in exactly the lists its split implies
    fit = pl.concat([v for k, v in lists.items() if k.startswith(("stage2", "test"))] + [ser_tr, ser_va]).unique("image")
    if len(fit) != len(df):
        raise SystemExit(f"{len(df) - len(fit)} final.csv rows are in no list; check split names")

    trainval = pl.concat([lists[k] for k in lists if not k.startswith("test")]).unique("image")
    test = pl.concat([lists[k] for k in lists if k.startswith("test")])
    path_overlap = set(trainval["image"]) & set(test["image"])
    grp = lambda d: set(zip(d["source"], d["group"]))
    group_overlap = grp(trainval) & grp(test)
    if path_overlap or group_overlap:
        raise SystemExit(f"test/train overlap: {len(path_overlap)} paths, {len(group_overlap)} groups e.g. {sorted(group_overlap)[:5]}")
    if test["image"].is_duplicated().any():
        raise SystemExit("an image appears in two test lists")

    SPLITS.mkdir(parents=True, exist_ok=True)
    for name, d in lists.items():
        write_list(name, d)
    write_yaml("stage1", "stage1_train", "stage1_val")
    write_yaml("stage2", "stage2_train", "stage2_val")

    summary = pl.DataFrame(
        [(k, len(v), int((v["role"] == "pos").sum()), int(v["n_drone"].sum()), int(v["n_bird"].sum()),
          int(v["n_airplane"].sum()), int(v["n_helicopter"].sum()), int((v["role"] == "bg").sum())) for k, v in lists.items()],
        schema=["list", "images", "pos_images", "drone", "bird", "airplane", "helicopter", "bg_images"], orient="row",
    )
    print(summary)
    s2 = lists["stage2_train"]
    vp = s2.group_by("viewpoint").agg(
        pl.len().alias("images"), (pl.col("role") == "pos").sum().alias("drone_images"), pl.col("n_drone").sum().alias("drone_boxes")
    ).sort("viewpoint")
    print("stage2_train by viewpoint:")
    print(vp)
    d = dict(zip(vp["viewpoint"], vp["drone_images"]))
    g2a, a2a = d.get("g2a", 0), d.get("a2a", 0)
    if max(g2a, a2a) > 2 * max(1, min(g2a, a2a)):
        print(f"WARNING: g2a/a2a drone images unbalanced ({g2a} vs {a2a}); decide manually (spec §5)")
    print(f"test/train overlap: 0 paths, 0 groups. lists -> {SPLITS}")


if __name__ == "__main__":
    main()
